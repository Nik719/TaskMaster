// Local-disk storage for attachments. Everything that touches the file system lives here,
// so moving to S3-compatible storage later means replacing this one module.
import { randomUUID } from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { env } from '../config/env.js';
import { logger } from '../config/logger.js';

export const uploadDir = env.UPLOAD_DIR;
fs.mkdirSync(uploadDir, { recursive: true });

/**
 * A random, collision-free file name. The extension is kept (lower-cased, alphanumeric only)
 * so files are recognisable on disk, but nothing else from the user's file name is used.
 */
export function newStorageKey(originalName) {
  const ext = path.extname(originalName).toLowerCase();
  return randomUUID() + (/^\.[a-z0-9]{1,10}$/.test(ext) ? ext : '');
}

/** Absolute path for a key. Keys are generated by us, but the check guards against bugs. */
export function pathFor(storageKey) {
  const full = path.join(uploadDir, storageKey);
  if (path.dirname(full) !== uploadDir) throw new Error('Invalid storage key');
  return full;
}

/** Best-effort delete: a missing file must never fail the request that removes its record. */
export async function removeFiles(storageKeys) {
  await Promise.all(
    storageKeys.map(async (key) => {
      try {
        await fs.promises.unlink(pathFor(key));
      } catch (err) {
        if (err.code !== 'ENOENT') logger.warn({ err, key }, 'Could not delete attachment file');
      }
    }),
  );
}
